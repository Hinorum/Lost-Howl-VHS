-- Очистка библиотеки кассет в базе (Postgres бота: Supabase и т.п.).
--
-- Зачем: источник правды — таблица story_cassettes, каталог на диске лишь
-- зеркало. bootstrap() при старте принимает файлы каталога в базу (_adopt_disk)
-- и выкладывает строки обратно в зеркало. Поэтому удаление файлов из
-- репозитория БЕЗ очистки строк не убирает кассеты из боя: старт вернёт их
-- из базы в диск, а диск вернёт в базу. Удалять надо пару «строка + файл»
-- (в панели это кнопка 🗑 на строке кассеты; здесь — ручная зачистка).
--
-- Порядок на боевом:
--   1) выполнить этот скрипт (строки исчезнут);
--   2) задеплоить коммит без кассет: деплой вытирает эфемерный диск, adopt
--      ничего не примет, sync ничего не выложит. Если задеплоить ДО очистки,
--      старт успеет принять файлы с диска обратно.
-- Обратной дороги нет: восстановление — повторный коммит кассет в репозиторий.

begin;

delete from story_cassettes;

-- Указатели панели больше не нужны: «следующая» плёнка и намерение правки.
delete from watcher_state
 where key in ('story_cassette_next', 'story_cassette_edit');

commit;

-- Проверка после выполнения: должно быть 0.
select count(*) as cassettes_left from story_cassettes;
