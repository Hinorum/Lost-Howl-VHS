"""Memo исходящих переводов: ячейка комментария и набор кандидатов,
по которым сверка ищет уже ушедший платёж в истории казначея."""

from __future__ import annotations

import logging

from ..cell import _comment_cell  # noqa: F401 — re-export для send.py

logger = logging.getLogger(__name__)

def _payout_comment_candidates(payout) -> list[str]:
    """Все комментарии, которыми эта выплата МОГЛА уйти в цепочку.

    Служебное memo «way:<день>:<тип>#<id>» уникально глобально — на нём держится
    анти-дубль. Свободный текст переопределения (возвраты при паузе) общий для
    многих выплат: если слать его как есть, два возврата с одинаковым текстом
    становятся НЕРАЗЛИЧИМЫ для сверки — таймаут вещания одной строки прочитается
    как «уже ушла» по чужому переводу, и игрок не получит деньги.

    Поэтому переопределение дополняется служебным суффиксом (уникальный ключ
    сохраняется даже у строки на 120 символов — сам текст усекается), а
    первичный кандидат идёт в цепочку.

    Список кандидатов — всегда из одной строки. До 2026-10-16 вторым
    кандидатом был сырой текст переопределения: так искались переводы,
    отправленные ДО введения суффикса (88ee317, 2026-09-21). Такие переводы
    видны сверке только в окне payout_reconcile_history_seconds (7 суток),
    значит с ~2026-09-28 сырой кандидат не находил ничего легитимного, зато
    расширял точное совпадение для КАЖДОГО нового возврата (лишний шанс
    отметить чужой перевод как «уже ушла»). Убран. Если окно сверки
    когда-нибудь расширят за пределы месяца — решение пересмотреть.
    """
    unique = f"way:{payout.round_id}:{payout.kind}#{payout.id}"
    override = payout.comment_override
    if not override:
        return [unique]
    suffix = f" | {unique}"
    available = max(0, 120 - len(suffix))
    return [f"{override[:available]}{suffix}"]
